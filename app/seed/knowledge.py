def _content_hash(content: str) -> str:
    """计算内容的 SHA-256 指纹，与 KnowledgeDocument.content_hash 对齐。"""
    return hashlib.sha256(content.encode("utf-8")).hexdigest()


async def seed_knowledge(db: AsyncSession) -> int:
    """写入医学知识种子文档，返回新建条数。

    幂等实现：按标题预查询已存在的文档，只插入缺失的。已存在的记录
    **不覆盖**——管理员可能已通过后台编辑过内容或审核状态，重跑种子
    脚本不应冲掉人工维护的数据。

    本函数只写 KnowledgeDocument 原始内容，不做分块或向量化。
    分块与 embedding 由 Celery 异步任务负责，理由见模块 docstring。
    """
    # 预查询已存在的标题集合
    existing_titles = set(
        (await db.execute(select(KnowledgeDocument.title))).scalars().all()
    )

    # 预查询科室 code -> id 映射，避免逐条查库
    from app.models.auth import Department  # 延迟导入避免循环依赖

    dept_rows = (
        await db.execute(select(Department.id, Department.code))
    ).all()
    dept_map: dict[str, object] = {code: did for did, code in dept_rows}

    created = 0
    for seed in _ALL_SEEDS:
        if seed.title in existing_titles:
            continue

        department_id = None
        if seed.department_code is not None:
            department_id = dept_map.get(seed.department_code)
            if department_id is None:
                logger.warning(
                    "知识文档 %r 引用的科室 code=%r 不存在，跳过关联",
                    seed.title,
                    seed.department_code,
                )

        db.add(
            KnowledgeDocument(
                title=seed.title,
                doc_type=seed.doc_type,
                content=seed.content,
                content_hash=_content_hash(seed.content),
                source=seed.source,
                source_url=seed.source_url,
                source_tier=seed.source_tier,
                department_id=department_id,
                extra_metadata=seed.extra_metadata,
                is_reviewed=False,
                is_active=True,
                index_status="pending",
            )
        )
        existing_titles.add(seed.title)
        created += 1

    await db.flush()
    logger.info(
        "知识种子数据：新建 %d 条，已存在 %d 条",
        created,
        len(_ALL_SEEDS) - created,
    )
    return created


